  function current() {
    try { return localStorage.getItem(KEY) || 'en'; } catch { return 'en'; }
  }
  function setLang(lang) {
    if (!dict[lang]) lang = 'en';
    try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
    if (typeof document !== 'undefined') {
      if (document.documentElement) document.documentElement.lang = lang;
      if (document.body) document.body.dataset.lang = lang;
    }
    return lang;
  }
  function t(key) {
    const lang = current();
    return (dict[lang] && dict[lang][key]) || dict.en[key] || key;
  }
  /* Replace {n} placeholders, e.g. t2('msg', {n: 2}) */
  function t2(key, vars) {
    let out = t(key);
    Object.keys(vars || {}).forEach(k => { out = out.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]); });
    return out;
  }

  window.IELTS_I18N = { dict, current, setLang, t, t2 };
